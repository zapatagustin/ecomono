#!/usr/bin/env node
// ecomono-skill-registry — generate .atl/skill-registry.md from SKILL.md frontmatter.
//
// Replaces `gentle-ai skill-registry refresh`. The registry is an INDEX the
// orchestrator reads to pick relevant skills and pass exact SKILL.md paths to
// sub-agents; it deliberately carries no summaries, since SKILL.md is the runtime
// contract and a summary would drift from it.
//
//   node ecomono-skill-registry.js [--cwd DIR] [--force] [--quiet] [--no-gitignore]
//
// Runs on every user prompt, so it fingerprints its inputs and exits early when
// nothing changed. Never fails the caller: any error is reported and exit 0.

const fs = require("fs");
const path = require("path");
const os = require("os");
const crypto = require("crypto");

const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n, d) => {
  const i = args.indexOf(n);
  return i >= 0 && args[i + 1] ? args[i + 1] : d;
};
const QUIET = flag("--quiet");
const FORCE = flag("--force");
const CWD = path.resolve(opt("--cwd", process.cwd()));
const say = (m) => { if (!QUIET) console.log(m); };

// Skill roots, most specific first — a project-level skill shadows a user-level
// one of the same name. HOME copies are the deployed tree; the repo copy is the
// source, and both are scanned so the registry works before and after a deploy.
const HOME = os.homedir();
const ROOTS = [
  { dir: path.join(CWD, "agent-skills"), scope: "project" },
  { dir: path.join(CWD, "skills"), scope: "project" },
  { dir: path.join(HOME, ".agents/skills"), scope: "user" },
  { dir: path.join(HOME, ".claude/skills"), scope: "user" },
];

/** Parse the leading `---` block. Only `name`, `description` and flags are needed. */
function frontmatter(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text);
  if (!m) return null;
  const out = {};
  let key = null;
  for (const raw of m[1].split(/\r?\n/)) {
    // A folded/literal block (`description: >`) continues on indented lines.
    if (key && /^\s+\S/.test(raw) && !/^\s*\w[\w-]*:/.test(raw)) {
      out[key] = out[key] ? out[key] + " " + raw.trim() : raw.trim();
      continue;
    }
    const kv = /^([\w-]+):\s*(.*)$/.exec(raw);
    if (!kv) { key = null; continue; }
    const [, k, v] = kv;
    if (v === ">" || v === "|" || v === "") { out[k] = ""; key = k; continue; }
    out[k] = v.replace(/^["']|["']$/g, "");
    key = k;
  }
  return out;
}

const truthy = (v) => v === true || v === "true" || v === "yes";

function collect() {
  const bySlug = new Map();
  const scanned = [];
  for (const { dir, scope } of ROOTS) {
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); }
    catch { continue; }
    scanned.push(dir);
    for (const e of entries) {
      if (!e.isDirectory() && !e.isSymbolicLink()) continue;
      const file = path.join(dir, e.name, "SKILL.md");
      let text;
      try { text = fs.readFileSync(file, "utf8"); } catch { continue; }
      const fm = frontmatter(text);
      if (!fm || !fm.name || !fm.description) continue;
      // Non-invocable support bundles are not selectable, so listing them would
      // only cost the delegator tokens.
      if (truthy(fm["disable-model-invocation"])) continue;
      if (bySlug.has(fm.name)) continue; // first root wins
      bySlug.set(fm.name, {
        name: fm.name,
        description: fm.description.replace(/\s+/g, " ").trim(),
        scope,
        // Resolve so the delegator can hand the path straight to a sub-agent.
        path: fs.realpathSync(file),
      });
    }
  }
  return { skills: [...bySlug.values()].sort((a, b) => a.name.localeCompare(b.name)), scanned };
}

function render(skills, scanned, stamp) {
  const rows = skills
    .map((s) => `| \`${s.name}\` | ${s.description.replace(/\|/g, "\\|")} | ${s.scope} | \`${s.path}\` |`)
    .join("\n");
  return `# Skill Registry — ecomono

<!-- Auto-generated by ecomono-skill-registry. Run with --force to regenerate. -->

Last updated: ${stamp}

## Sources scanned

${scanned.map((d) => `- ${d}`).join("\n")}

## Contract

**Delegator use only.** This registry is an index, not a summary. Any agent that launches subagents reads it to select relevant skills, then passes exact \`SKILL.md\` paths for the subagent to read before work.

\`SKILL.md\` remains the source of truth. Do not inject generated summaries or compact rules by default; pass paths so subagents load the full runtime contract.

## Skills

| Skill | Trigger / description | Scope | Path |
| --- | --- | --- | --- |
${rows}

## Loading protocol

1. Match task context and target files against the \`Trigger / description\` column.
2. Pass only the matching \`Path\` values to the subagent under \`## Skills to load before work\`.
3. Instruct the subagent to read those exact \`SKILL.md\` files before reading, writing, reviewing, testing, or creating artifacts.
4. If no matching skill exists, proceed without project skill injection and report \`skill_resolution: none\`.
`;
}

function main() {
  const { skills, scanned } = collect();
  if (!skills.length) { say("skill registry: no skills found — nothing written"); return; }

  const outDir = path.join(CWD, ".atl");
  const outFile = path.join(outDir, "skill-registry.md");
  const cacheFile = path.join(outDir, ".skill-registry.cache.json");

  // Fingerprint the selected set, not the file bodies: the registry only carries
  // name/description/scope/path, so a body edit cannot change the output.
  const fingerprint = crypto
    .createHash("sha256")
    .update(JSON.stringify(skills))
    .digest("hex");

  if (!FORCE && fs.existsSync(outFile)) {
    try {
      if (JSON.parse(fs.readFileSync(cacheFile, "utf8")).fingerprint === fingerprint) {
        say(`skill registry up to date (cache-hit): ${outFile}`);
        return;
      }
    } catch { /* no or bad cache — regenerate */ }
  }

  // The fingerprint gates the write, so the date only moves when the skill set
  // actually changed — a daily run on an unchanged registry produces no diff.
  const stamp = new Date().toISOString().slice(0, 10);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(outFile, render(skills, scanned, stamp));
  fs.writeFileSync(cacheFile, JSON.stringify({ fingerprint }) + "\n");
  say(`skill registry refreshed (${skills.length} skills): ${outFile}`);
}

if (require.main === module) {
  if (flag("--selftest")) { selftest(); }
  else {
    try { main(); } catch (e) { if (!QUIET) console.error("skill registry: " + e.message); }
    process.exit(0);
  }
}

// ── runnable check ──────────────────────────────────────────────────────────
function selftest() {
  const assert = require("assert");

  // frontmatter: quoted one-liner
  let fm = frontmatter('---\nname: a\ndescription: "hi there"\n---\nbody');
  assert.strictEqual(fm.name, "a");
  assert.strictEqual(fm.description, "hi there");

  // frontmatter: folded block joins continuation lines
  fm = frontmatter("---\nname: b\ndescription: >\n  one two\n  three\n---\n");
  assert.strictEqual(fm.description, "one two three");

  // frontmatter: a following key ends the folded block
  fm = frontmatter("---\nname: c\ndescription: >\n  text\nlicense: MIT\n---\n");
  assert.strictEqual(fm.description, "text");
  assert.strictEqual(fm.license, "MIT");

  // frontmatter: nested metadata must not be swallowed into description
  fm = frontmatter("---\nname: d\ndescription: x\nmetadata:\n  author: someone\n---\n");
  assert.strictEqual(fm.description, "x");

  // missing frontmatter
  assert.strictEqual(frontmatter("no frontmatter here"), null);

  // flags
  assert.ok(truthy("true") && truthy(true) && !truthy("false") && !truthy(undefined));

  // render: escapes pipes so a description cannot break the table
  const out = render(
    [{ name: "n", description: "a | b", scope: "user", path: "/p/SKILL.md" }],
    ["/root"], "2026-01-01");
  assert.ok(out.includes("a \\| b"), "pipe must be escaped");
  assert.ok(out.includes("| `n` |") && out.includes("| user |"));
  assert.ok(out.includes("Last updated: 2026-01-01"));

  console.log("ecomono-skill-registry selftest: all assertions passed");
}
